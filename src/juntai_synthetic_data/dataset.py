"""Canonical in-memory dataset used by the synchronous service."""

from __future__ import annotations

import math
from collections.abc import Mapping
from dataclasses import dataclass
from datetime import date, datetime
from typing import Any

from juntai_synthetic_data.contracts.models import (
    FieldSpec,
    FieldType,
    GenerationContract,
    canonical_digest,
    canonical_json,
)
from juntai_synthetic_data.errors import ErrorCode, SyntheticDataError


@dataclass(frozen=True)
class GeneratedDataset:
    records: Mapping[str, tuple[dict[str, Any], ...]]
    record_count: int
    byte_count: int
    data_digest: str


def _valid_value(value: Any, spec: FieldSpec) -> bool:
    if value is None:
        return spec.nullable
    if spec.type is FieldType.STRING:
        return isinstance(value, str)
    if spec.type is FieldType.INTEGER:
        return isinstance(value, int) and not isinstance(value, bool)
    if spec.type is FieldType.NUMBER:
        return (
            isinstance(value, (int, float))
            and not isinstance(value, bool)
            and (not isinstance(value, float) or math.isfinite(value))
        )
    if spec.type is FieldType.BOOLEAN:
        return isinstance(value, bool)
    if spec.type is FieldType.DATE:
        if not isinstance(value, str):
            return False
        try:
            date.fromisoformat(value)
        except ValueError:
            return False
        return True
    if spec.type is FieldType.DATETIME:
        if not isinstance(value, str):
            return False
        try:
            datetime.fromisoformat(value.replace("Z", "+00:00"))
        except ValueError:
            return False
        return True
    return False


def validate_generated_dataset(
    contract: GenerationContract,
    records: Mapping[str, tuple[dict[str, Any], ...]],
) -> GeneratedDataset:
    specs = {record.record_type: record for record in contract.records}
    if set(records) != set(specs):
        raise SyntheticDataError(
            ErrorCode.CONTRACT_INVALID,
            "provider returned an unexpected set of record types",
        )
    for record_type, spec in specs.items():
        rows = records[record_type]
        if len(rows) != spec.count:
            raise SyntheticDataError(
                ErrorCode.CONTRACT_INVALID,
                "provider returned a record count different from the contract",
                details={"record_type": record_type},
            )
        unique_values: dict[str, set[object]] = {
            name: set() for name, field in spec.fields.items() if field.unique
        }
        for row in rows:
            if set(row) != set(spec.fields):
                raise SyntheticDataError(
                    ErrorCode.CONTRACT_INVALID,
                    "provider returned fields different from the contract",
                    details={"record_type": record_type},
                )
            for name, field in spec.fields.items():
                value = row[name]
                if not _valid_value(value, field):
                    raise SyntheticDataError(
                        ErrorCode.CONTRACT_INVALID,
                        "provider returned a value with an incompatible structural type",
                        details={"record_type": record_type, "field": name},
                    )
                if field.unique and value is not None:
                    if value in unique_values[name]:
                        raise SyntheticDataError(
                            ErrorCode.CONTRACT_INVALID,
                            "provider returned duplicate values for a unique field",
                            details={"record_type": record_type, "field": name},
                        )
                    unique_values[name].add(value)
    for relation in contract.relations:
        source_type, source_field = relation.from_field.split(".", 1)
        target_type, target_field = relation.to_field.split(".", 1)
        target_values = {row[target_field] for row in records[target_type]}
        for row in records[source_type]:
            value = row[source_field]
            if value is None and not relation.required:
                continue
            if value not in target_values:
                raise SyntheticDataError(
                    ErrorCode.CONTRACT_INVALID,
                    "provider returned a relation value without a declared target",
                    details={"relation": f"{relation.from_field}->{relation.to_field}"},
                )
    document = {
        "contract_digest": contract.digest,
        "records": [
            {"record_type": spec.record_type, "rows": list(records[spec.record_type])}
            for spec in contract.records
        ],
    }
    encoded = canonical_json(document)
    if len(encoded) > contract.bounds.max_bytes:
        raise SyntheticDataError(ErrorCode.OUTPUT_LIMIT_EXCEEDED, "generated bytes exceed bound")
    return GeneratedDataset(
        records={name: tuple(rows) for name, rows in records.items()},
        record_count=sum(len(rows) for rows in records.values()),
        byte_count=len(encoded),
        data_digest=canonical_digest(document),
    )
